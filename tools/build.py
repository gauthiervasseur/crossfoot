#!/usr/bin/env python3
"""Build Crossfoot (BI for AFP): regenerate generated assets, then package the app and the website.

    python3 tools/build.py

Steps
  1. app/css/fonts.css     - Libre Franklin embedded as a data: URL (works from file://)
  2. app/samples/*         - demo dataset (tools/make_demo_data.py)
  3. app/themes/*.css      - example theme files, extracted from js/theme.js
  4. dist/Crossfoot-<v>.zip    - the downloadable app (folder "Crossfoot/")
  5. dist/Crossfoot-<v>.dmg    - native macOS app (tools/build_mac.py; Macs only)
     (Windows: tools/build_windows.ps1 on a PC, or the GitHub workflow, gives Crossfoot-<v>-Setup.exe)
  6. website/              - landing page + live copy of the app in website/play/
                             + zip and dmg in website/download/
"""
import base64
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app"
SITE = ROOT / "website"
DIST = ROOT / "dist"


def version():
    m = re.search(r"VERSION = '([^']+)'", (APP / "js" / "app.js").read_text())
    return m.group(1)


def build_fonts():
    # Libre Franklin (OFL) stands in for AFP's Franklin Gothic; Franklin Gothic is used first when installed.
    faces = [("Libre Franklin", "LibreFranklin-Variable.ttf", "100 900")]
    css = ["/* Generated by tools/build.py - fonts under the SIL Open Font License (see fonts/). */"]
    for family, file, weight in faces:
        data = base64.b64encode((APP / "fonts" / file).read_bytes()).decode()
        css.append(
            "@font-face { font-family: '%s'; src: url(data:font/ttf;base64,%s) format('truetype'); "
            "font-weight: %s; font-display: block; }" % (family, data, weight)
        )
    (APP / "css" / "fonts.css").write_text("\n".join(css) + "\n")


def build_themes():
    src = (APP / "js" / "theme.js").read_text()
    out = APP / "themes"
    out.mkdir(exist_ok=True)
    for const, name in (("AFP", "afp"), ("AFP_NIGHT", "afp-night"), ("ARCADE", "arcade"), ("CORPORATE", "corporate")):
        m = re.search(r"const %s = `(.*?)`;" % const, src, re.S)
        (out / f"{name}.css").write_text(m.group(1))
    # A third example that shows web fonts and plain CSS fallbacks.
    (out / "editorial-webfont.css").write_text(
        """/* Crossfoot theme example: web fonts + plain CSS properties.
 * @import works when the computer is online; otherwise the fallbacks are used.
 */
@import url("https://fonts.googleapis.com/css2?family=IBM+Plex+Sans:wght@400;600&family=IBM+Plex+Serif:wght@600&display=swap");

:root {
  --crossfoot-theme-name: "Editorial";
  font-family: "IBM Plex Sans", "Helvetica Neue", Arial, sans-serif;   /* plain property works too */
  --crossfoot-title-font-family: "IBM Plex Serif", Georgia, serif;
  --crossfoot-font-size: 14px;
  --crossfoot-title-font-size: 18px;
  color: #1d1d1b;
  background: #f7f4ee;
  --crossfoot-grid-color: #e4ded2;
  --crossfoot-color-1: #2a78d6;
  --crossfoot-color-2: #eb6834;
  --crossfoot-color-3: #1baf7a;
  --crossfoot-color-4: #eda100;
  --crossfoot-color-5: #e87ba4;
  --crossfoot-color-6: #008300;
  --crossfoot-color-7: #6250d6;
  --crossfoot-color-8: #e34948;
  --crossfoot-sequential: #fbe3d6, #9c3a12;
  --crossfoot-table-header-background: #1d1d1b;
  --crossfoot-table-header-color: #f7f4ee;
}
"""
    )


def write_readme(target):
    v = version()
    (target / "README.txt").write_text(f"""CROSSFOOT {v} - business intelligence for finance CSV files, made for AFP
=========================================================================

START
  Double-click index.html. It opens in your web browser (Chrome, Edge,
  Firefox or Safari). Nothing to install, no internet needed, and your data
  never leaves your computer.

USE
  1. Load CSV (or drop a .csv file onto the window). Try samples/meridian-debt-book.csv.
  2. Drag fields from the left onto Columns, Rows, Values and Color.
  3. Pick a chart type, or leave Auto.
  4. Drop fields on Filters to filter. Use the swap button to pivot rows and columns.
  5. Click a pill to change Sum/Average/... or Year/Month/...

THEMES
  The default theme uses AFP's colours. Theme CSS loads a .css file with your
  own colors and fonts. Examples are in themes/. Supported variables are
  listed in the Theme tab and in themes/afp.css.

SAVE / OPEN
  Save writes a .crossfoot.json file with your sheets, filters and theme (not the
  data). Open it, then load the matching CSV.

CREDITS
  Charts: plotly.js (MIT license) - vendor/
  Font: Libre Franklin (SIL Open Font License) - fonts/. Franklin Gothic is used when installed.
  Demo data: fictional (Meridian Components debt book) - every entity, bank and
  number is made up.

TIP
  Month-end balances are stocks: they add up within a month, not across
  months. Filter Month End to one month, or chart them by month.
""")


def package():
    v = version()
    DIST.mkdir(exist_ok=True)
    zpath = DIST / f"Crossfoot-{v}.zip"
    staging = DIST / "Crossfoot"
    if staging.exists():
        shutil.rmtree(staging)
    shutil.copytree(APP, staging, ignore=shutil.ignore_patterns(".DS_Store", "*.ttf", "icon-mac-1024.png"))
    # Raw TTFs are dropped (already embedded in fonts.css); the OFL licence files stay.
    write_readme(staging)
    if zpath.exists():
        zpath.unlink()
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in sorted(staging.rglob("*")):
            if p.is_file():
                z.write(p, Path("Crossfoot") / p.relative_to(staging))
    shutil.rmtree(staging)
    return zpath


def build_site(zpath, dmg=None):
    play = SITE / "play"
    if play.exists():
        shutil.rmtree(play)
    shutil.copytree(APP, play, ignore=shutil.ignore_patterns(".DS_Store", "*.ttf", "icon-mac-1024.png"))
    dl = SITE / "download"
    if dl.exists():
        shutil.rmtree(dl)
    dl.mkdir(parents=True)
    shutil.copy2(zpath, dl / zpath.name)
    shutil.copy2(zpath, dl / "Crossfoot-latest.zip")
    if dmg is None:  # not built this run (e.g. not on a Mac): reuse the last one, if any
        dmg = DIST / f"Crossfoot-{version()}.dmg"
        dmg = dmg if dmg.exists() else None
    if dmg:
        shutil.copy2(dmg, dl / dmg.name)
        shutil.copy2(dmg, dl / "Crossfoot-latest.dmg")
    # Windows installer and zip: built on a PC or by the GitHub workflow (tools/build_windows.ps1), then dropped in dist/.
    for kind, latest in ((f"Crossfoot-{version()}-Setup.exe", "Crossfoot-latest-Setup.exe"),
                         (f"Crossfoot-{version()}-Windows.zip", "Crossfoot-latest-Windows.zip")):
        if (DIST / kind).exists():
            shutil.copy2(DIST / kind, dl / kind)
            shutil.copy2(DIST / kind, dl / latest)
    for name in ("afp.css", "afp-night.css", "arcade.css", "corporate.css", "editorial-webfont.css"):
        shutil.copy2(APP / "themes" / name, dl / name)
    shutil.copy2(APP / "samples" / "meridian-debt-book.csv", dl / "meridian-debt-book.csv")
    assets = SITE / "assets"
    assets.mkdir(exist_ok=True)
    for f in ("favicon.ico", "icon-32.png", "icon-64.png", "icon-128.png", "icon-180.png", "icon-256.png", "icon-512.png"):
        shutil.copy2(APP / "assets" / f, assets / f)
    shutil.copy2(APP / "css" / "fonts.css", assets / "fonts.css")
    # Stamp version + size into the landing page.
    idx = SITE / "index.html"
    if idx.exists():
        html = idx.read_text()
        size = "%.1f MB" % (zpath.stat().st_size / 1e6)
        html = re.sub(r'(<span data-version>)[^<]*(</span>)', r"\g<1>%s\g<2>" % version(), html)
        html = re.sub(r'(<span data-size>)[^<]*(</span>)', r"\g<1>%s\g<2>" % size, html)
        if dmg:
            dsize = "%.1f MB" % (dmg.stat().st_size / 1e6)
            html = re.sub(r'(<span data-size-dmg>)[^<]*(</span>)', r"\g<1>%s\g<2>" % dsize, html)
        idx.write_text(html)


def main():
    subprocess.run([sys.executable, str(ROOT / "tools" / "make_demo_data.py")], check=True)
    subprocess.run([sys.executable, str(ROOT / "tools" / "make_icon.py")], check=True)
    build_fonts()
    build_themes()
    zpath = package()
    sys.path.insert(0, str(ROOT / "tools"))
    import build_mac
    dmg = build_mac.main(version())
    build_site(zpath, dmg)
    print("built", zpath.relative_to(ROOT), "and website/")


if __name__ == "__main__":
    main()
